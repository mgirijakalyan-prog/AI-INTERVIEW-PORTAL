// NEXT QUESTION
// ======================================================

nextButton.addEventListener(
    "click",
    function () {

        if (!selectedAnswer) {

            alert(
                "Please select an answer first."
            );

            return;

        }


        currentQuestion++;


        if (
            currentQuestion <
            questions.length
        ) {

            loadQuestion();

        }

        else {

            showResult();

        }

    }
);


// ======================================================
// SHOW RESULT
// ======================================================

function showResult() {

    const percentage =
        Math.round(
            (score / questions.length) * 100
        );


    // ==================================================
    // SAVE PRACTICE COMPLETION
    // ==================================================

    let practiceCount =
        Number(
            localStorage.getItem(
                "practiceCount"
            )
        ) || 0;


    practiceCount++;


    localStorage.setItem(
        "practiceCount",
        practiceCount
    );


    // ==================================================
    // SAVE LATEST PERFORMANCE
    // ==================================================

    localStorage.setItem(
        "latestScore",
        percentage
    );


    localStorage.setItem(
        "lastActivity",
        "Practice - " + currentCategory
    );


    // ==================================================
    // RESULT DETAILS
    // ==================================================

    const wrong =
        questions.length - score;


    finalScore.textContent =
        `${percentage}%`;


    correctAnswers.textContent =
        score;


    wrongAnswers.textContent =
        wrong;


    // ==================================================
    // RESULT MESSAGE
    // ==================================================

    if (percentage === 100) {

        resultMessage.textContent =
            "Excellent! You answered everything correctly.";

    }

    else if (percentage >= 70) {

        resultMessage.textContent =
            "Great job! Keep practicing to improve further.";

    }

    else if (percentage >= 50) {

        resultMessage.textContent =
            "Good effort. A little more practice will help.";

    }

    else {

        resultMessage.textContent =
            "Keep practicing. You can improve with more preparation.";

    }


    // ==================================================
    // HIDE QUESTION AREA
    // ==================================================

    questionNumber.style.display =
        "none";

    scoreText.style.display =
        "none";

    questionText.style.display =
        "none";

    optionsContainer.style.display =
        "none";

    nextButton.style.display =
        "none";


    // ==================================================
    // SHOW RESULT
    // ==================================================

    resultBox.style.display =
        "block";

}


