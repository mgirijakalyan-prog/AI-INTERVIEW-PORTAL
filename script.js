// ======================================================
// GET ATTEMPTED QUESTION INDEXES
// ======================================================

function getAttemptedQuestions(category) {

    const storageKey =
        ATTEMPTED_KEY_PREFIX + category;

    const saved =
        localStorage.getItem(storageKey);

    if (!saved) {
        return [];
    }

    try {

        const parsed =
            JSON.parse(saved);

        if (Array.isArray(parsed)) {
            return parsed;
        }

        return [];

    } catch (error) {

        console.error(
            "Could not read attempted questions:",
            error
        );

        return [];

    }

}


// ======================================================
// SAVE ATTEMPTED QUESTION INDEXES
// ======================================================

function saveAttemptedQuestions(category, indexes) {

    const storageKey =
        ATTEMPTED_KEY_PREFIX + category;

    localStorage.setItem(
        storageKey,
        JSON.stringify(indexes)
    );

}


// ======================================================
// GET RANDOM QUESTIONS
// ======================================================

function getRandomQuestions(category) {

    const allQuestions =
        questionData[category];

    let attempted =
        getAttemptedQuestions(category);

    // Remove invalid old indexes if the database changes.
    attempted =
        attempted.filter(function (index) {

            return (
                Number.isInteger(index) &&
                index >= 0 &&
                index < allQuestions.length
            );

        });


    // ==================================================
    // IF ALL QUESTIONS HAVE BEEN ATTEMPTED
    // START A NEW CYCLE
    // ==================================================

    if (attempted.length >= allQuestions.length) {

        attempted = [];

        saveAttemptedQuestions(
            category,
            attempted
        );

    }


    // ==================================================
    // FIND QUESTIONS NOT YET ATTEMPTED
    // ==================================================

    const availableIndexes =
        allQuestions
            .map(function (_, index) {
                return index;
            })
            .filter(function (index) {
                return !attempted.includes(index);
            });


    // ==================================================
    // SHUFFLE AVAILABLE QUESTIONS
    // ==================================================

    for (
        let i = availableIndexes.length - 1;
        i > 0;
        i--
    ) {

        const randomIndex =
            Math.floor(
                Math.random() * (i + 1)
            );

        const temp =
            availableIndexes[i];

        availableIndexes[i] =
            availableIndexes[randomIndex];

        availableIndexes[randomIndex] =
            temp;

    }


    // Select 5 or whatever remains in this cycle.
    const selectedIndexes =
        availableIndexes.slice(
            0,
            QUESTIONS_PER_SESSION
        );


    // Save these questions as attempted.
    const updatedAttempted =
        [...attempted, ...selectedIndexes];

    saveAttemptedQuestions(
        category,
        updatedAttempted
    );


    // Return actual question objects.
    return selectedIndexes.map(function (index) {

        return allQuestions[index];

    });

}


// ======================================================
// START NEW PRACTICE SESSION
// ======================================================

function startNewPracticeSession() {

    currentQuestion = 0;

    score = 0;

    selectedAnswer = false;


    // Get fresh questions.
    questions =
        getRandomQuestions(currentCategory);


    // Make sure the result screen is hidden.
    resultBox.style.display = "none";


    questionNumber.style.display =
        "inline";

    scoreText.style.display =
        "inline";

    questionText.style.display =
        "block";

    optionsContainer.style.display =
        "flex";

    nextButton.style.display =
        "inline-block";


    loadQuestion();

}


// ======================================================
// LOAD QUESTION
// ======================================================

function loadQuestion() {

    selectedAnswer = false;


    const current =
        questions[currentQuestion];


    questionNumber.textContent =
        `Question ${currentQuestion + 1} of ${questions.length}`;


    questionText.textContent =
        current.question;


    scoreText.textContent =
        `Score: ${score}`;


    optionsContainer.innerHTML = "";


    current.options.forEach(function (option) {

        const button =
            document.createElement("button");


        button.classList.add("option");


        button.textContent =
            option;


        button.addEventListener(
            "click",
            function () {

                checkAnswer(
                    button,
                    option
                );

            }
        );


        optionsContainer.appendChild(button);

    });

}


// ======================================================
// CHECK ANSWER
// ======================================================

function checkAnswer(
    button,
    selectedOption
) {

    if (selectedAnswer) {
        return;
    }


    selectedAnswer = true;


    const correctAnswer =
        questions[currentQuestion].answer;


    if (
        selectedOption ===
        correctAnswer
    ) {

        button.style.backgroundColor =
            "#dcfce7";

        button.style.borderColor =
            "#16a34a";

        score++;

    }

    else {

        button.style.backgroundColor =
            "#fee2e2";

        button.style.borderColor =
            "#dc2626";


        const allOptions =
            document.querySelectorAll(
                ".option"
            );


        allOptions.forEach(
            function (option) {

                if (
                    option.textContent ===
                    correctAnswer
                ) {

                    option.style.backgroundColor =
                        "#dcfce7";

                    option.style.borderColor =
                        "#16a34a";

                }

            }
        );

    }


    scoreText.textContent =
        `Score: ${score}`;

}


